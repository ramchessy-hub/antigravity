/*
# Device Balance Tracking Tables

1. New Tables
- `devices`: Stores each synced device with its ID, token, and display name/order.
  - `id` (uuid, PK)
  - `device_id` (text, unique) — the identifier generated by the Tampermonkey script (e.g. "device-2efmowx")
  - `token` (text) — shared token for authenticating sync requests
  - `display_name` (text) — friendly name for UI
  - `sort_order` (int) — custom ordering for display
  - `daily_target` (numeric, default 0.16) — per-device daily earnings target
  - `last_balance` (numeric) — most recent reported balance
  - `last_seen_at` (timestamptz) — last successful sync timestamp
  - `is_online` (boolean) — whether device is considered live
  - `today_earnings` (numeric) — earnings accumulated today
  - `created_at` (timestamptz)

- `balance_reports`: Historical record of each balance sync.
  - `id` (uuid, PK)
  - `device_id` (text, not null) — references devices.device_id
  - `balance` (numeric, not null) — balance at time of report
  - `reported_at` (timestamptz, default now())

2. Security
- Enable RLS on all tables.
- Allow anon + authenticated CRUD since this is a single-tenant monitoring app with token-based auth via the edge function.
- The edge function uses the service role key (bypasses RLS) for writes.
- The frontend reads via anon key.

3. Notes
- `devices` table is the primary entity; `balance_reports` provides history.
- The edge function upserts device rows on each sync and inserts a report row.
- `sort_order` allows the custom device ordering the user specified.
*/

CREATE TABLE IF NOT EXISTS devices (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  device_id text UNIQUE NOT NULL,
  token text,
  display_name text,
  sort_order int DEFAULT 999,
  daily_target numeric DEFAULT 0.16,
  last_balance numeric,
  last_seen_at timestamptz,
  is_online boolean DEFAULT false,
  today_earnings numeric DEFAULT 0,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE devices ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "anon_select_devices" ON devices;
CREATE POLICY "anon_select_devices" ON devices FOR SELECT
TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_devices" ON devices;
CREATE POLICY "anon_insert_devices" ON devices FOR INSERT
TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_devices" ON devices;
CREATE POLICY "anon_update_devices" ON devices FOR UPDATE
TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_devices" ON devices;
CREATE POLICY "anon_delete_devices" ON devices FOR DELETE
TO anon, authenticated USING (true);

CREATE TABLE IF NOT EXISTS balance_reports (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  device_id text NOT NULL,
  balance numeric NOT NULL,
  reported_at timestamptz DEFAULT now()
);

ALTER TABLE balance_reports ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "anon_select_reports" ON balance_reports;
CREATE POLICY "anon_select_reports" ON balance_reports FOR SELECT
TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_reports" ON balance_reports;
CREATE POLICY "anon_insert_reports" ON balance_reports FOR INSERT
TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_reports" ON balance_reports;
CREATE POLICY "anon_update_reports" ON balance_reports FOR UPDATE
TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_reports" ON balance_reports;
CREATE POLICY "anon_delete_reports" ON balance_reports FOR DELETE
TO anon, authenticated USING (true);

CREATE INDEX IF NOT EXISTS idx_balance_reports_device_id ON balance_reports(device_id);
CREATE INDEX IF NOT EXISTS idx_balance_reports_reported_at ON balance_reports(reported_at);
CREATE INDEX IF NOT EXISTS idx_devices_sort_order ON devices(sort_order);
